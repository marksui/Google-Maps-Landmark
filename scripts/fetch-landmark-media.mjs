function extractArray(name, source) {
  const match = source.match(new RegExp(`const ${name} = (\\[[\\s\\S]*?\\]);`));
  if (!match) {
    throw new Error(`Could not find ${name} in app.js`);
  }
  return match[1];
}

function parseLandmarks(source) {
  const continentSet = new Set(continents);
  const countrySet = new Set(countries);
  const citySet = new Set(Object.keys(cityCoordinates));
  const records = [];
  let currentContinent = "";
  let currentCountry = "";
  let currentCity = "";

  source
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .forEach((line) => {
      if (continentSet.has(line)) {
        currentContinent = line;
        currentCountry = "";
        currentCity = "";
        return;
      }

      const isCountry = countrySet.has(line);
      const isCity = citySet.has(line);

      if (isCountry && (!isCity || line !== currentCountry || Boolean(currentCity))) {
        currentCountry = line;
        currentCity = "";
        return;
      }

      if (isCity) {
        currentCity = line;
        return;
      }

      if (!currentContinent || !currentCountry || !currentCity) {
        return;
      }

      records.push({
        id: slugify(`${currentContinent}-${currentCountry}-${currentCity}-${line}-${records.length}`),
        name: line,
        continent: currentContinent,
        country: currentCountry,
        city: currentCity,
      });
    });

  return records;
}

async function findLandmarkMedia(landmark) {
  let textFallback = null;

  for (const query of mediaQueries(landmark)) {
    const result = await findMedia(query);
    if (result?.thumbnail) {
      return result;
    }
    textFallback ||= result;
  }

  const wikidataResult = await findWikidataMedia(landmark);
  if (wikidataResult?.thumbnail) {
    return wikidataResult;
  }
  textFallback ||= wikidataResult;

  const commonsResult = await findCommonsMedia(landmark);
  if (commonsResult) {
    return {
      ...commonsResult,
      description: textFallback?.description || commonsResult.description,
    };
  }

  return textFallback;
}

function mediaQueries(landmark) {
  const aliases = QUERY_ALIASES[`${landmark.name}|${landmark.city}`] || [];
  return [
    ...aliases,
    `${landmark.name} ${landmark.city} ${landmark.country}`,
    `${landmark.name} ${landmark.city}`,
    landmark.name,
  ];
}

async function findMedia(query) {
  const params = new URLSearchParams({
    action: "query",
    format: "json",
    generator: "search",
    gsrsearch: query,
    gsrlimit: "8",
    prop: "pageimages|extracts|info",
    pithumbsize: "320",
    exintro: "1",
    explaintext: "1",
    exsentences: "2",
    inprop: "url",
    origin: "*",
  });

  const payload = await fetchJson(`${WIKI_API}?${params}`);
  if (!payload) {
    return null;
  }
  const pages = Object.values(payload.query?.pages || {}).sort(
    (a, b) => (a.index || 99) - (b.index || 99),
  );
  const best = pages.find((page) => page.thumbnail?.source) || pages.find((page) => page.extract);

  if (!best) {
    return null;
  }

  const description = firstSentence(best.extract || "");
  return {
    title: best.title,
    thumbnail: best.thumbnail?.source || "",
    pageUrl: best.fullurl || `https://en.wikipedia.org/?curid=${best.pageid}`,
    description,
  };
}

async function findWikidataMedia(landmark) {
  const searches = [`${landmark.name} ${landmark.city}`, landmark.name];

  for (const search of searches) {
    const params = new URLSearchParams({
      action: "wbsearchentities",
      format: "json",
      language: "en",
      uselang: "en",
      limit: "8",
      origin: "*",
      search,
    });

    const payload = await fetchJson(`${WIKIDATA_API}?${params}`);
    if (!payload) {
      continue;
    }
    const candidate = (payload.search || []).find((item) => isLikelyMatch(landmark, item));
    if (!candidate?.id) {
      continue;
    }

    const entity = await getWikidataEntity(candidate.id);
    const imageName = entity?.claims?.P18?.[0]?.mainsnak?.datavalue?.value;
    const label = entity?.labels?.en?.value || candidate.label || landmark.name;
    const descriptionText = entity?.descriptions?.en?.value || candidate.description || "";
    const enwikiTitle = entity?.sitelinks?.enwiki?.title;

    if (!imageName && !descriptionText) {
      continue;
    }

    return {
      title: label,
      thumbnail: imageName
        ? `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(imageName)}?width=320`
        : "",
      pageUrl: enwikiTitle
        ? `https://en.wikipedia.org/wiki/${encodeURIComponent(enwikiTitle.replaceAll(" ", "_"))}`
        : `https://www.wikidata.org/wiki/${candidate.id}`,
      description: descriptionText ? sentenceFromDescription(label, descriptionText) : "",
    };
  }

  return null;
}

async function findCommonsMedia(landmark) {
  for (const query of mediaQueries(landmark)) {
    const params = new URLSearchParams({
      action: "query",
      format: "json",
      list: "search",
      srnamespace: "6",
      srlimit: "8",
      origin: "*",
      srsearch: query,
    });

    const payload = await fetchJson(`${COMMONS_API}?${params}`);
    const file = (payload?.query?.search || []).find((item) =>
      /\.(jpe?g|png|webp)$/i.test(item.title),
    );

    if (!file) {
      continue;
    }

    const filename = file.title.replace(/^File:/, "");
    return {
      title: filename.replace(/\.[^.]+$/, "").replaceAll("_", " "),
      thumbnail: `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(filename)}?width=320`,
      pageUrl: `https://commons.wikimedia.org/wiki/${encodeURIComponent(file.title.replaceAll(" ", "_"))}`,
      description: "",
    };
  }

  return null;
}

async function getWikidataEntity(id) {
  const params = new URLSearchParams({
    action: "wbgetentities",
    format: "json",
    ids: id,
    props: "claims|labels|descriptions|sitelinks",
    languages: "en",
    sitefilter: "enwiki",
    origin: "*",
  });

  const payload = await fetchJson(`${WIKIDATA_API}?${params}`);
  return payload.entities?.[id] || null;
}

async function fetchJson(url) {
  for (let attempt = 0; attempt < 3; attempt += 1) {
    await delay(120 + attempt * 220);
    const response = await fetch(url, {
      headers: { "User-Agent": USER_AGENT },
    });

    if (response.ok) {
      return response.json();
    }

    if (![429, 500, 502, 503, 504].includes(response.status)) {
      return null;
    }

    await delay(1000 * (attempt + 1));
  }

  return null;
}

function delay(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

function isLikelyMatch(landmark, item) {
  const name = normalize(landmark.name);
  const label = normalize(item.label || "");
  const aliasText = normalize((item.aliases || []).join(" "));
  const description = normalize(item.description || "");
  const location = normalize(`${landmark.city} ${landmark.country}`);

  if (!label) {
    return false;
  }

  if (label === name || name.includes(label) || label.includes(name)) {
    return true;
  }

  const meaningfulNameWords = name.split(" ").filter((word) => word.length > 3);
  const sharedWords = meaningfulNameWords.filter((word) => label.includes(word) || aliasText.includes(word));
  if (meaningfulNameWords.length >= 2 && sharedWords.length >= Math.min(2, meaningfulNameWords.length)) {
    return true;
  }

  return sharedWords.length >= 1 && description.includes(location.split(" ")[0]);
}

function normalize(value) {
  return String(value)
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function sentenceFromDescription(label, description) {
  const cleanDescription = description.replace(/\s+/g, " ").trim();
  if (!cleanDescription) {
    return "";
  }
  if (/[.!?]$/.test(cleanDescription)) {
    return cleanDescription;
  }
  return `${label} is ${cleanDescription}.`;
}

function firstSentence(text) {
  return text
    .replace(/\s+/g, " ")
    .split(/(?<=[.!?])\s+/)
    .slice(0, 1)
    .join(" ")
    .trim();
}

async function runWithConcurrency(items, limit, worker) {
  const queue = [...items];
  const workers = Array.from({ length: limit }, async () => {
    while (queue.length) {
      const item = queue.shift();
      await worker(item);
    }
  });
  await Promise.all(workers);
}

function slugify(value) {
  return value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
